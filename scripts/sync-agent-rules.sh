#!/bin/bash
# Rebuilds AGENTS.md from rules/always. Strips YAML frontmatter. Does not copy scoped rules.
# Also refreshes .cursor/rules/*.mdc as symlinks to the source rules.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/AGENTS.md"
ALWAYS="$ROOT/rules/always"
SCOPED="$ROOT/rules/scoped"
CURSOR="$ROOT/.cursor/rules"

strip_frontmatter() {
  awk '
    BEGIN { state = 0 }
    state == 0 && $0 == "---" { state = 1; next }
    state == 1 && $0 == "---" { state = 2; next }
    state == 1 { next }
    { print }
  ' "$1"
}

preferred=(
  repo.md
  architecture.md
  response-style.md
  safety.md
  simple-answers.md
  thinking-questions.md
  vortex-verification.md
)

files=()
for name in "${preferred[@]}"; do
  if [[ -f "$ALWAYS/$name" ]]; then
    files+=("$ALWAYS/$name")
  fi
done

shopt -s nullglob
for file in "$ALWAYS"/*.md; do
  base="$(basename "$file")"
  skip=0
  for name in "${preferred[@]}"; do
    if [[ "$base" == "$name" ]]; then
      skip=1
      break
    fi
  done
  if [[ "$skip" -eq 0 ]]; then
    files+=("$file")
  fi
done

TMP="$(mktemp)"
{
  cat <<'EOF'
# Agent rules

Edit the files in `rules/always/`, then run `scripts/sync-agent-rules.sh`.
Do not edit this file by hand. Scoped rules stay in `rules/scoped/` and are not copied here.

These rules are hard. If a tool default conflicts with them, follow these rules for response style, folder boundaries, and dev state safety.

EOF
  for file in "${files[@]}"; do
    strip_frontmatter "$file"
    printf '\n'
  done
} > "$TMP"

mv "$TMP" "$OUT"
printf 'Wrote %s\n' "$OUT"

mkdir -p "$CURSOR"
expected="$(mktemp)"
link_rule() {
  local src="$1"
  local name rel_src
  name="$(basename "$src" .md)"
  rel_src="${src#"$ROOT"/}"
  ln -sfn "../../${rel_src}" "$CURSOR/${name}.mdc"
  printf '%s\n' "${name}.mdc" >> "$expected"
  printf 'Linked .cursor/rules/%s.mdc -> ../../%s\n' "$name" "$rel_src"
}

for file in "$ALWAYS"/*.md "$SCOPED"/*.md; do
  link_rule "$file"
done

for link in "$CURSOR"/*.mdc; do
  base="$(basename "$link")"
  if ! grep -Fxq "$base" "$expected"; then
    rm -f "$link"
    printf 'Removed stale .cursor/rules/%s\n' "$base"
  fi
done
rm -f "$expected"
