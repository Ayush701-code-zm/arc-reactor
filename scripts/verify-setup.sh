#!/bin/bash
# Checks agent rules, Cursor symlinks, and the safety hook.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
fail=0

ok() { printf 'ok %s\n' "$1"; }
bad() { printf 'FAIL %s\n' "$1"; fail=1; }

for f in hooks/block-dangerous.sh hooks/self-check.sh scripts/sync-agent-rules.sh .githooks/pre-push scripts/gen-proto.sh; do
  if [[ -x "$f" ]]; then ok "exec $f"; else bad "exec $f"; fi
done

if [[ -f .git/config ]] && grep -q 'hooksPath = .githooks' .git/config; then
  ok "hooksPath"
elif [[ ! -d .git ]]; then
  printf 'skip hooksPath (no git repo yet). You do: git init && git config core.hooksPath .githooks\n'
else
  printf 'skip hooksPath (not enabled). You do: git config core.hooksPath .githooks\n'
fi

if [[ -f .cursor/hooks.json && -f .gitignore ]]; then
  ok "hook configs"
else
  bad "hook configs"
fi

if grep -q 'hooks/denied.log' .gitignore; then ok "gitignore log"; else bad "gitignore log"; fi

python3 - <<'PY'
import os, sys
root = os.getcwd()
pairs = [
    (".cursor/rules/repo.mdc", "rules/always/repo.md"),
    (".cursor/rules/architecture.mdc", "rules/always/architecture.md"),
    (".cursor/rules/response-style.mdc", "rules/always/response-style.md"),
    (".cursor/rules/safety.mdc", "rules/always/safety.md"),
    (".cursor/rules/simple-answers.mdc", "rules/always/simple-answers.md"),
    (".cursor/rules/go-control-plane.mdc", "rules/scoped/go-control-plane.md"),
    (".cursor/rules/cpp-runtime.mdc", "rules/scoped/cpp-runtime.md"),
    (".cursor/rules/proto-contract.mdc", "rules/scoped/proto-contract.md"),
]
bad = False
for link, target in pairs:
    if not os.path.lexists(link):
        print(f"FAIL link missing {link}")
        bad = True
        continue
    real = os.path.realpath(link)
    expect = os.path.realpath(target)
    if real != expect:
        print(f"FAIL link {link} -> {real}")
        bad = True
    else:
        print(f"ok link {link}")
sys.exit(1 if bad else 0)
PY
[[ $? -eq 0 ]] || fail=1

if grep -q 'Do not edit this file by hand' AGENTS.md \
  && grep -q 'Dev state' AGENTS.md \
  && grep -q 'Milestone 1' AGENTS.md \
  && ! grep -q 'alwaysApply:' AGENTS.md \
  && ! grep -q 'Hinglish' AGENTS.md; then
  ok "AGENTS.md synced"
else
  bad "AGENTS.md synced"
fi

for f in \
  rules/always/repo.md \
  rules/always/architecture.md \
  rules/always/response-style.md \
  rules/always/safety.md \
  rules/always/simple-answers.md \
  rules/scoped/go-control-plane.md \
  rules/scoped/cpp-runtime.md \
  rules/scoped/proto-contract.md
do
  [[ -f "$f" ]] && ok "file $f" || bad "file $f"
done

bash hooks/self-check.sh || fail=1

zero="0000000000000000000000000000000000000000"
new_sha="0123456789abcdef0123456789abcdef01234567"
set +e
printf 'refs/heads/new %s refs/heads/new %s\n' "$new_sha" "$zero" | .githooks/pre-push origin url >/dev/null
code=$?
set -e
if [[ "$code" -eq 0 ]]; then ok "pre-push new branch"; else bad "pre-push new branch ($code)"; fi

set +e
printf 'refs/heads/old %s refs/heads/old %s\n' "$zero" "$new_sha" | .githooks/pre-push origin url >/dev/null
code=$?
set -e
if [[ "$code" -ne 0 ]]; then ok "pre-push delete"; else bad "pre-push delete allowed"; fi

if git rev-parse --verify HEAD >/dev/null 2>&1; then
  head_sha="$(git rev-parse HEAD)"
  empty="$(git hash-object -t tree /dev/null)"
  set +e
  printf 'refs/heads/main %s refs/heads/main %s\n' "$head_sha" "$empty" | .githooks/pre-push origin url >/dev/null
  code=$?
  set -e
  if [[ "$code" -ne 0 ]]; then ok "pre-push non-ff"; else bad "pre-push non-ff allowed"; fi
else
  ok "pre-push non-ff skipped (no commits)"
fi

if [[ "$fail" -ne 0 ]]; then
  printf 'verify failed\n'
  exit 1
fi
printf 'verify passed\n'
